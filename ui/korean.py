def ko(value: Any) -> Any:
    if not isinstance(value, str) or value == "":
        return value
    if value in _EXACT:
        return _EXACT[value]

    text = value
    for english, korean in _PHRASES:
        text = text.replace(english, korean)

    text = re.sub(r"\bnone\b", "없음", text)
    text = re.sub(r"\bauto\b", "자동", text)
    return text


def _translate_choices(choices: Any) -> Any:
    if not isinstance(choices, (list, tuple)):
        return choices

    translated = []
    changed = False
    for choice in choices:
        if isinstance(choice, tuple) and choice:
            display = ko(choice[0])
            translated.append((display, *choice[1:]))
            changed = changed or display != choice[0]
        elif isinstance(choice, str):
            display = ko(choice)
            if display != choice:
                translated.append((display, choice))
                changed = True
            else:
                translated.append(choice)
        else:
            translated.append(choice)
    return translated if changed else choices


def _translate_kwargs(kwargs: dict[str, Any]) -> dict[str, Any]:
    if "label" in kwargs:
        kwargs["label"] = ko(kwargs["label"])
    if "info" in kwargs:
        kwargs["info"] = ko(kwargs["info"])
    if "placeholder" in kwargs:
        kwargs["placeholder"] = ko(kwargs["placeholder"])
    if "choices" in kwargs:
        kwargs["choices"] = _translate_choices(kwargs["choices"])
    return kwargs


def _wrap_component(original: Any, mode: str = "default") -> Any:
    @wraps(original)
    def wrapper(*args: Any, **kwargs: Any) -> Any:
        args = list(args)

        if mode in {"markdown", "button", "label_first"} and args:
            args[0] = ko(args[0])
        elif mode == "choices_first" and args:
            args[0] = _translate_choices(args[0])

        kwargs = _translate_kwargs(dict(kwargs))

        if mode == "button" and "value" in kwargs:
            kwargs["value"] = ko(kwargs["value"])
        if mode == "markdown" and "value" in kwargs:
            kwargs["value"] = ko(kwargs["value"])

        return original(*args, **kwargs)

    return wrapper


def install_gradio_korean(gr: Any) -> None:
    if getattr(gr, "_mangatl_korean_installed", False):
        return
    gr._mangatl_korean_installed = True

    for name in ("Dropdown", "Radio", "CheckboxGroup"):
        if hasattr(gr, name):
            setattr(gr, name, _wrap_component(getattr(gr, name), "choices_first"))

    for name in (
        "Textbox",
        "Image",
        "File",
        "Slider",
        "Number",
        "Checkbox",
        "Gallery",
    ):
        if hasattr(gr, name):
            setattr(gr, name, _wrap_component(getattr(gr, name)))

    for name in ("Accordion", "TabItem"):
        if hasattr(gr, name):
            setattr(gr, name, _wrap_component(getattr(gr, name), "label_first"))

    if hasattr(gr, "Button"):
        gr.Button = _wrap_component(gr.Button, "button")
    if hasattr(gr, "Markdown"):
        gr.Markdown = _wrap_component(gr.Markdown, "markdown")

    original_update = gr.update

    @wraps(original_update)
    def update_wrapper(**kwargs: Any) -> Any:
        return original_update(**_translate_kwargs(dict(kwargs)))

    gr.update = update_wrapper

    # Do not wrap gr.Error / gr.Warning / gr.Info.
    # In Gradio, gr.Error is also used as an exception class in code such as
    # ``except gr.Error as e``.  Replacing it with a function breaks exception
    # handling with: "catching classes that do not inherit from BaseException".
    # UI labels and component text are translated above; error message text is
    # translated at call sites or by the existing callbacks where safe.
